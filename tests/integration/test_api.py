def totp_for(secret: str = ADMIN_TOTP_SECRET) -> str:
    """The code an authenticator would show right now."""
    from veyl_api.security.mfa import totp_now

    return totp_now(secret)


def login(client, admin, *, password: str | None = None, code: str | None = None):
    """Sign in as the test administrator, supplying the current TOTP code.

    Kept as a helper so the many tests that just need a session do not each have
    to know about the second factor. Tests that care about the factor call
    ``client.post`` directly.
    """
    payload = {
        "email": admin["user"].email,
        "password": admin["password"] if password is None else password,
    }
    if code is not False:
        payload["totp_code"] = totp_for(admin.get("totp", ADMIN_TOTP_SECRET)) if code is None else code
    return client.post("/api/auth/login", json=payload)


def login_as(client, email: str, secret: str, *, password: str = STRONG_PASSWORD, **extra):
    """Sign in as any account whose TOTP secret the test knows."""
    return client.post(
        "/api/auth/login",
        json={
            "email": email,
            "password": password,
            "totp_code": totp_for(secret),
            **extra,
        },
    )


