def test_a_challenge_is_single_use(client, auth_headers, session):
    """Replaying a challenge must fail — this is the replay defence."""
    from veyl_api.models import AuthChallenge
    from veyl_api.security.mfa import MFAError
    from veyl_api.security.webauthn import consume_challenge

    body = client.post("/api/auth/webauthn/register/options", headers=auth_headers).json()
    consume_challenge(session, challenge=body["challenge"], purpose="registration")
    session.commit()

    with pytest.raises(MFAError, match="already been used"):
        consume_challenge(session, challenge=body["challenge"], purpose="registration")

    assert session.execute(select(AuthChallenge)).scalars().first() is not None


