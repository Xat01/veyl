def _minimal_attestation_object() -> str:
    """A well-formed CBOR attestation object: ``{"fmt": "none", "authData": <37 zeros>}``.

    Shared by the origin tests so that the check under test is the one that
    fails, rather than an earlier parse error standing in for it.
    """
    import base64

    auth_data = b"\x00" * 37
    cbor = (
        b"\xa2"
        b"\x63fmt"  # text(3) "fmt"
        b"\x64none"  # text(4) "none"
        b"\x68authData"  # text(8) "authData"
        b"\x58\x25" + auth_data  # byte string, 1-byte length, 37 items
    )
    return base64.urlsafe_b64encode(cbor).decode().rstrip("=")


def test_a_webauthn_registration_with_a_forged_payload_is_refused(client, auth_headers):
    """No partial trust: a payload that does not verify is never stored.

    The attestation object is well-formed, so the origin check is what rejects
    it rather than an earlier parse failure. Testing the origin rule requires
    getting past the format rules first.
    """
    import base64
    import json as _json

    options = client.post(
        "/api/auth/webauthn/register/options", headers=auth_headers
    ).json()

    client_data = {
        "type": "webauthn.create",
        "challenge": options["challenge"],
        "origin": "https://attacker.example",  # not an allowed origin
    }
    forged_client_data = base64.urlsafe_b64encode(
        _json.dumps(client_data).encode()
    ).decode().rstrip("=")

    response = client.post(
        "/api/auth/webauthn/register",
        headers=auth_headers,
        json={
            "credential_id": "A" * 32,
            "client_data_json": forged_client_data,
            "attestation_object": _minimal_attestation_object(),
            "label": "Forged",
        },
    )
    assert response.status_code == 400, response.text
    assert "origin" in response.json()["detail"].lower()

    posture = client.get("/api/auth/security", headers=auth_headers).json()
    assert posture["has_hardware_key"] is False


