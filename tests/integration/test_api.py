def test_a_member_with_a_factor_can_be_promoted_to_admin(client, auth_headers, session):
    """The policy is a requirement, not a prohibition."""
    from veyl_api.api.routes.auth import _hash_totp_secret
    from veyl_api.security.mfa import generate_totp_secret, hash_recovery_codes

    email = f"promotable-{uuid.uuid4().hex[:6]}@acmepay.example"
    created = client.post(
        "/api/members",
        headers=auth_headers,
        json={
            "email": email,
            "password": STRONG_PASSWORD,
            "full_name": "Promotable",
            "role": "ENGINEER",
        },
    ).json()

    session.expire_all()
    user = session.execute(select(User).where(User.email == email)).scalar_one()
    user.mfa_enabled = True
    user.mfa_secret_hash = _hash_totp_secret(generate_totp_secret())
    user.mfa_recovery_hash = hash_recovery_codes(["AAAA-BBBB"])
    session.commit()

    response = client.patch(
        f"/api/members/{created['id']}", headers=auth_headers, json={"role": "ADMIN"}
    )
    assert response.status_code == 200, response.text
    assert response.json()["role"] == "ADMIN"


